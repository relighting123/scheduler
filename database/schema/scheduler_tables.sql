-- 학습(Input) 데이터 공통: RULE_TIMEKEY (YYYYMMDDHHMMSS, 예: 20251020070000)
-- 동일 테이블에 여러 RULE_TIMEKEY 스냅샷이 공존할 수 있음

-- 1. 제품별 공정 수순 정보 및 재공 정보
CREATE TABLE WIP_INFO (
    RULE_TIMEKEY VARCHAR2(14),
    PLAN_PROD_KEY VARCHAR2(50),
    OPER_ID VARCHAR2(50),
    OPER_SEQ NUMBER,
    WIP_QTY NUMBER,
    CONSTRAINT PK_WIP_INFO PRIMARY KEY (RULE_TIMEKEY, PLAN_PROD_KEY, OPER_ID)
);

-- 2. 제품별 공정별 장비 모델별 시간당 생산량
CREATE TABLE UPH_INFO (
    RULE_TIMEKEY VARCHAR2(14),
    PLAN_PROD_KEY VARCHAR2(50),
    OPER_ID VARCHAR2(50),
    EQP_MODEL_CD VARCHAR2(50),
    UPH NUMBER,
    CONSTRAINT PK_UPH_INFO PRIMARY KEY (RULE_TIMEKEY, PLAN_PROD_KEY, OPER_ID, EQP_MODEL_CD)
);

-- 3. 제품별 공정별 장비 모델별 시간대별 댓수
CREATE TABLE EQP_QTY_INFO (
    RULE_TIMEKEY VARCHAR2(14),
    BATCH_ID VARCHAR2(50),
    EQP_MODEL_CD VARCHAR2(50),
    TIME_SLOT VARCHAR2(20), -- e.g., '2026051707'
    EQP_QTY NUMBER,
    CONSTRAINT PK_EQP_QTY_INFO PRIMARY KEY (RULE_TIMEKEY, BATCH_ID, EQP_MODEL_CD, TIME_SLOT)
);

-- 5. 제품별 공정별 장비 모델별 처리가능여부
CREATE TABLE AVAIL_INFO (
    RULE_TIMEKEY VARCHAR2(14),
    PLAN_PROD_KEY VARCHAR2(50),
    OPER_ID VARCHAR2(50),
    EQP_MODEL_CD VARCHAR2(50),
    AVAIL_YN VARCHAR2(1),
    CONSTRAINT PK_AVAIL_INFO PRIMARY KEY (RULE_TIMEKEY, PLAN_PROD_KEY, OPER_ID, EQP_MODEL_CD)
);

-- 6. Tool 교체 단위 정보 (Batch_ID N:1 매핑)
CREATE TABLE BATCH_TOOL_INFO (
    RULE_TIMEKEY VARCHAR2(14),
    BATCH_ID VARCHAR2(50),
    PLAN_PROD_KEY VARCHAR2(50),
    OPER_ID VARCHAR2(50),
    CONSTRAINT PK_BATCH_TOOL_INFO PRIMARY KEY (RULE_TIMEKEY, PLAN_PROD_KEY, OPER_ID)
);

-- 7. Tool 갯수 정보
CREATE TABLE TOOL_QTY_INFO (
    RULE_TIMEKEY VARCHAR2(14),
    BATCH_ID VARCHAR2(50),
    EQP_MODEL_CD VARCHAR2(50),
    TOOL_QTY NUMBER,
    CONSTRAINT PK_TOOL_QTY_INFO PRIMARY KEY (RULE_TIMEKEY, BATCH_ID, EQP_MODEL_CD)
);

-- 8. 계획 정보
CREATE TABLE PLAN_INFO (
    RULE_TIMEKEY VARCHAR2(14),
    PLAN_PROD_KEY VARCHAR2(50),
    OPER_ID VARCHAR2(50),
    START_TIME VARCHAR2(20),
    END_TIME VARCHAR2(20),
    PLAN_QTY NUMBER,
    CONSTRAINT PK_PLAN_INFO PRIMARY KEY (RULE_TIMEKEY, PLAN_PROD_KEY, OPER_ID, START_TIME, END_TIME)
);

-- Output 결과물 테이블
CREATE TABLE RTD_CONV_INF (
    RULE_TIMEKEY VARCHAR2(20),
    FROM_BATCH VARCHAR2(50),
    FROM_PLAN_PROD_KEY VARCHAR2(50),
    FROM_OPER_ID VARCHAR2(50),
    EQP_MODEL_CD VARCHAR2(50),
    TO_BATCH_ID VARCHAR2(50),
    TO_PLAN_PROD_KEY VARCHAR2(50),
    TO_OPER_ID VARCHAR2(50),
    START_CONV_TIME VARCHAR2(20),
    EQP_QTY NUMBER
);

CREATE TABLE RTD_CONV_HI AS SELECT * FROM RTD_CONV_INF WHERE 1=0;

-- RTS 결과 마스터 (추론 Output)
CREATE TABLE RTS_RSLT_MAS (
    RULE_TIMEKEY       VARCHAR2(50)      NOT NULL,
    EQP_ID             VARCHAR2(50)      NOT NULL,
    EQP_MODEL_CD       VARCHAR2(50),
    START_TM           VARCHAR2(14),
    END_TM             VARCHAR2(14),
    PLAN_PROD_ATTR_VAL VARCHAR2(200),
    PROD_QTY           VARCHAR2(50),
    CUM_PROD_QTY       VARCHAR2(50),
    CRT_USET_ID        VARCHAR2(50),
    CRT_TM             VARCHAR2(14),
    CONSTRAINT PK_RTS_RSLT_MAS PRIMARY KEY (RULE_TIMEKEY, EQP_ID)
);

COMMENT ON TABLE  RTS_RSLT_MAS                         IS 'RTS 결과 마스터';
COMMENT ON COLUMN RTS_RSLT_MAS.RULE_TIMEKEY            IS '룰 타임키';
COMMENT ON COLUMN RTS_RSLT_MAS.EQP_ID                  IS '설비 ID';
COMMENT ON COLUMN RTS_RSLT_MAS.EQP_MODEL_CD            IS '설비 모델 코드';
COMMENT ON COLUMN RTS_RSLT_MAS.START_TM                IS '시작 시간 (YYYYMMDDHHMMSS)';
COMMENT ON COLUMN RTS_RSLT_MAS.END_TM                  IS '종료 시간 (YYYYMMDDHHMMSS)';
COMMENT ON COLUMN RTS_RSLT_MAS.PLAN_PROD_ATTR_VAL      IS '계획 생산 속성 값';
COMMENT ON COLUMN RTS_RSLT_MAS.PROD_QTY                IS '생산 수량';
COMMENT ON COLUMN RTS_RSLT_MAS.CUM_PROD_QTY            IS '누적 생산 수량';
COMMENT ON COLUMN RTS_RSLT_MAS.CRT_USET_ID             IS '생성 사용자 ID';
COMMENT ON COLUMN RTS_RSLT_MAS.CRT_TM                  IS '생성 시간 (YYYYMMDDHHMMSS)';

